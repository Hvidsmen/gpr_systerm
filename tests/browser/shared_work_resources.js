const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const c = JSON.parse(process.env.SHARED_RESOURCE_BROWSER_CONFIG);
(async () => {
 const browser = await chromium.launch({executablePath:c.chromium,headless:true,args:['--no-sandbox']});
 try {
  const context = await browser.newContext({viewport:{width:1600,height:1100}});
  await context.route('**/*',r=>{
   const url=r.request().url();
   if(url.startsWith(c.base))return r.continue();
   if(process.env.BROWSER_BOOTSTRAP_CSS&&url.endsWith('/bootstrap.min.css'))return r.fulfill({contentType:'text/css',body:fs.readFileSync(process.env.BROWSER_BOOTSTRAP_CSS)});
   return r.abort();
  });
  await context.addCookies([{name:'sessionid',value:c.gpr_cookie,url:c.base}]);
  const page = await context.newPage(), errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(c.base+c.gpr,{waitUntil:'networkidle'});
  const expand=page.locator('[data-expand-allocations]').first();
  if(!await expand.isVisible())await page.getByRole('button',{name:'Ещё',exact:true}).first().click();
  await expand.click();
  const host = item => page.locator('[data-work-resource-target][data-resource-item="'+item+'"]');
  const token = item => 'item:'+c.work+':'+item;
  const editor = () => page.locator('[data-inline-resource-editor]');
  const save = async () => {
   const response=page.waitForResponse(r=>r.url().includes('/resource-assignment/')&&r.request().method()==='POST');
   await editor().getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
   const result=await response;
   assert.ok(result.ok(),await result.text());
   const data=await result.json();
   await editor().waitFor({state:'detached'});
   return data.assignment;
  };
  await host(c.a).locator('[data-add-resource=equipment]').click();
  assert.equal(await editor().locator('input[name=targets][value="'+token(c.a)+'"]').isChecked(),true);
  await editor().locator('input[name=targets][value="'+token(c.b)+'"]').check();
  await editor().locator('[name=equipment_type]').selectOption(String(c.equipment));
  await editor().locator('[name=end_date]').fill('2026-01-02');
  let assignment=await save();
  assert.equal(assignment.shared,true);assert.equal(assignment.targets.length,2);
  for(const item of [c.a,c.b])assert.equal(await host(item).locator('[data-resource-card="'+assignment.id+'"]').count(),1);
  assert.equal(await page.locator('#resource-rows-equipment [data-generated-resource="'+assignment.id+'"]').count(),1);
  await host(c.b).locator('[data-resource-card="'+assignment.id+'"] [data-shared-resource] summary').click();
  assert.equal(await host(c.b).locator('[data-resource-card="'+assignment.id+'"] [data-shared-resource] li').count(),2);
  await host(c.b).locator('[data-resource-card="'+assignment.id+'"]').getByRole('button',{name:'Изменить',exact:true}).click();
  assert.equal(await editor().locator('input[name=targets]:checked').count(),2);
  await editor().locator('[name=count]').fill('3');
  assignment=await save();assert.equal(assignment.count,3);
  for(const item of [c.a,c.b])assert.ok((await host(item).locator('[data-resource-card="'+assignment.id+'"] p').first().textContent()).includes('3'));
  await host(c.a).locator('[data-resource-card="'+assignment.id+'"]').getByRole('button',{name:'Изменить',exact:true}).click();
  await editor().locator('input[name=targets][value="'+token(c.b)+'"]').uncheck();
  assignment=await save();assert.equal(assignment.shared,false);
  assert.equal(await host(c.b).locator('[data-resource-card="'+assignment.id+'"]').count(),0);
  assert.equal(await page.locator('#resource-rows-equipment [data-generated-resource="'+assignment.id+'"]').count(),1);
  assert.equal(await host(c.a).locator('[data-add-resource=fuel]').count(),0);
  await page.goto(c.base+c.graph);
  await page.locator('[data-graph-add=fuel]').click();
  assert.equal(await editor().locator('[data-resource-target-picker]').isVisible(),false);
  await editor().locator('[name=fuel_type]').selectOption('DIESEL');
  await editor().locator('[name=daily_liters]').fill('10');
  await editor().locator('[name=end_date]').fill('2026-01-02');
  const fuel=await save();assert.equal(fuel.targets.length,0);
  assert.equal(await page.locator('[data-graph-fuel] .rg-node').count(),1);
  await page.screenshot({path:'/tmp/shared-resource-gpr.png',fullPage:false});
  await context.addCookies([{name:'sessionid',value:c.cookie,url:c.base}]);
  await page.goto(c.base+c.smg,{waitUntil:'networkidle'});
  const form=page.locator('form').filter({has:page.getByRole('button',{name:'Сохранить назначение',exact:true})});
  await form.locator('[name=target_scope]').selectOption('works');
  await form.locator('input[name=targets][value="'+token(c.a)+'"]').check();
  await form.locator('input[name=targets][value="'+token(c.b)+'"]').check();
  await form.locator('[name=equipment_type]').selectOption(String(c.equipment),{force:true});
  await form.locator('[name=count]').fill('2');
  await form.locator('[name=shifts_per_day]').fill('2');
  await form.locator('[name=end_date]').fill('2026-01-02');
  const response=page.waitForResponse(r=>r.url().includes('/resources/')&&r.request().method()==='POST');
  await form.getByRole('button',{name:'Сохранить назначение',exact:true}).click();
  assert.equal((await response).status(),302);
  await page.getByText('Назначение сохранено. Потребность в экипаже рассчитана на каждую смену.',{exact:true}).waitFor();
  assert.equal(await page.locator('.work-resource-shared').count(),1);
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/shared-resource-smg-mobile.png',fullPage:false});
  assert.deepEqual(errors,[]);
  console.log('PASS: choose several works; one GPR allocation visible under each; one summary row; edit from secondary work; unlink without duplication; object-only fuel; manager saves shared SMG assignment');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
