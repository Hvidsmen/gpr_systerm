const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const c = JSON.parse(process.env.CATALOGUE_BROWSER_CONFIG);
(async () => {
 const browser = await chromium.launch({executablePath:c.chromium,headless:true,args:['--no-sandbox']});
 try {
  const context = await browser.newContext({viewport:{width:1500,height:950}});
  await context.route('**/*', route => {
   const url = route.request().url();
   if (url.startsWith(c.base)) return route.continue();
   if (process.env.CATALOGUE_BOOTSTRAP_CSS && url.endsWith('/bootstrap.min.css')) return route.fulfill({contentType:'text/css',body:fs.readFileSync(process.env.CATALOGUE_BOOTSTRAP_CSS)});
   if (process.env.CATALOGUE_ICONS_CSS && url.endsWith('/bootstrap-icons.css')) return route.fulfill({contentType:'text/css',body:fs.readFileSync(process.env.CATALOGUE_ICONS_CSS)});
   return route.abort();
  });
  await context.addCookies([{name:'sessionid',value:c.cookie,url:c.base}]);
  const page = await context.newPage();
  const errors = [];page.on('pageerror', e => errors.push(e.message));
  await page.goto(c.base+c.list);
  await page.locator('.catalogue-tree').waitFor();
  assert.equal(await page.locator('.catalogue-advanced').getAttribute('open'),null);
  assert.equal(await page.locator('[data-bulk-contextual]').isVisible(),false);
  await page.locator('#id_q').fill('кабельной');
  await page.getByRole('button',{name:'Найти',exact:true}).click();
  await page.locator('mark').first().waitFor();
  const hit = page.locator('[data-search-hit]');
  assert.equal(await hit.count(),1);
  assert.ok(await hit.isVisible());
  assert.equal(await hit.locator('mark').textContent(),'кабельной');
  const treeWork = page.locator('[data-tree-key="work-'+c.work+'"]');
  assert.equal(await treeWork.evaluate(n => n.open),true);
  const titleSizes = await page.locator('.ct-heading>a,.ct-item-name>a').evaluateAll(nodes => [...new Set(nodes.map(n => getComputedStyle(n).fontSize))]);
  assert.deepEqual(titleSizes,['14px']);
  await page.locator('[data-bulk-row]').first().check();
  assert.equal(await page.locator('[data-bulk-contextual]').isVisible(),true);
  await page.locator('[data-bulk-clear]').click();
  assert.equal(await page.locator('[data-bulk-contextual]').isVisible(),false);
  const menuButton = page.locator('#work-menu-'+c.work).locator('..').locator('[data-row-menu]');
  await menuButton.click();
  assert.equal(await menuButton.getAttribute('aria-expanded'),'true');
  await page.keyboard.press('Escape');
  assert.equal(await menuButton.getAttribute('aria-expanded'),'false');
  assert.ok(await menuButton.evaluate(n => n === document.activeElement));
  await page.screenshot({path:'/tmp/catalogue-ux-search.png',fullPage:false});
  const targetLink = page.locator('a[href$="#work-item-'+c.last+'"]').first();
  await targetLink.scrollIntoViewIfNeeded();
  const scrollBefore = await page.evaluate(() => window.scrollY);
  await targetLink.click();
  await page.locator('#work-structure-form').waitFor();
  assert.ok(page.url().endsWith('#work-item-'+c.last));
  await page.getByRole('link',{name:'← Вернуться к списку',exact:true}).click();
  await page.locator('.catalogue-tree').waitFor();
  await page.waitForFunction(before => Math.abs(window.scrollY-before)<80,scrollBefore);
  assert.equal(await page.locator('[data-tree-key="work-'+c.work+'"]').evaluate(n => n.open),true);
  await page.locator('[data-search-hit]').click();
  await page.locator('#work-structure-form').waitFor();
  await page.locator('#work-structure-form[data-dirty]').waitFor();
  await page.locator('[name=norm_'+c.a+']').fill('4');
  await page.getByText('Есть изменения',{exact:true}).waitFor();
  await page.locator('[name=share_'+c.a+']').fill('10');
  await page.locator('[name=share_'+c.b+']').fill('10');
  assert.equal(await page.locator('[data-share-status]').getAttribute('data-valid'),'false');
  await page.getByRole('button',{name:'Сохранить состав',exact:true}).click();
  await page.getByText('Сумма долей всех работ комплекса должна быть 100%.',{exact:true}).waitFor();
  assert.equal(await page.locator('[name=norm_'+c.a+']').inputValue(),'4');
  await page.locator('[name=share_'+c.a+']').fill('25');
  await page.locator('[name=share_'+c.b+']').fill('75');
  assert.equal(await page.locator('[data-share-status]').getAttribute('data-valid'),'true');
  await page.getByRole('button',{name:'Сохранить состав',exact:true}).click();
  await page.getByText('Состав работ сохранён. Доли стоимости — 100%.',{exact:true}).waitFor();
  assert.equal(await page.locator('[data-save-state]').textContent(),'Сохранено');
  await page.screenshot({path:'/tmp/catalogue-ux-detail.png',fullPage:false});
  // Unsaved navigation uses the browser's native warning and can be cancelled.
  await page.locator('[name=norm_'+c.a+']').fill('5');
  let warned = false;page.once('dialog',async dialog => {warned=true;await dialog.dismiss();});
  await page.getByRole('link',{name:'← Вернуться к списку',exact:true}).click({noWaitAfter:true});
  await page.waitForFunction(() => document.querySelector('[name^=norm_]').value === '5');
  assert.ok(warned);
  await page.locator('[name=norm_'+c.a+']').fill('4,000');
  // Return the exact initial localized value before leaving the form.
  if (await page.locator('[data-catalogue-edit]').getAttribute('data-dirty') === 'true') {
   page.once('dialog', dialog => dialog.accept());
  }
  await page.getByRole('link',{name:'← Вернуться к списку',exact:true}).click();
  await page.locator('.catalogue-tree').waitFor();
  await page.getByRole('link',{name:'Таблица',exact:true}).click();
  await page.locator('.catalogue-list-table').waitFor();
  assert.ok(page.url().includes('q='));
  assert.ok(await page.locator('.catalogue-found-items mark').isVisible());
  await page.goto(c.base+c.list+'complex-objects/'+c.facility+'/?view=table');
  const complexItem = page.locator('a[href$="#work-item-'+c.last+'"]').first();
  await complexItem.scrollIntoViewIfNeeded();
  const complexScroll = await page.evaluate(() => window.scrollY);
  await complexItem.click();
  await page.locator('#work-structure-form').waitFor();
  await page.getByRole('link',{name:'← Вернуться к списку',exact:true}).click();
  await page.locator('.catalogue-list-table').waitFor();
  await page.waitForFunction(before => Math.abs(window.scrollY-before)<80,complexScroll);
  assert.ok(page.url().includes('/complex-objects/'));
  await page.setViewportSize({width:390,height:844});
  await page.goto(c.base+c.list+'?q='+encodeURIComponent('кабельной')+'&view=tree');
  await page.locator('[data-search-hit]').waitFor();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
  assert.equal(overflow,false,'No horizontal page overflow on a narrow screen');
  await page.screenshot({path:'/tmp/catalogue-ux-mobile.png',fullPage:false});
  await page.goto(c.base+c.detail);
  await page.locator('#work-structure-form').waitFor();
  await page.evaluate(() => window.scrollTo(0,document.body.scrollHeight));
  const actionBox = await page.getByRole('button',{name:'Сохранить состав',exact:true}).boundingBox();
  assert.ok(actionBox.y >= 0 && actionBox.y+actionBox.height <= 844,'Save stays on screen on mobile');
  await page.screenshot({path:'/tmp/catalogue-ux-mobile-detail.png',fullPage:false});
  await page.goto(c.base+c.detail+'update/');
  await page.locator('[data-catalogue-edit][data-dirty=false]').waitFor();
  assert.equal(await page.locator('[data-save-state]').textContent(),'Сохранено');
  await page.locator('#id_name').fill('Изменённое название без сохранения');
  await page.getByText('Есть изменения',{exact:true}).waitFor();
  page.once('dialog',dialog => dialog.accept());
  await page.goto(c.base+c.detail);
  await context.addCookies([{name:'sessionid',value:c.observerCookie,url:c.base}]);
  await page.goto(c.base+c.detail);
  assert.equal(await page.locator('[data-catalogue-edit]').count(),0);
  assert.equal(await page.getByRole('button',{name:'Сохранить состав',exact:true}).count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: search expands and highlights; equal title sizes; contextual bulk actions; keyboard menus; return restores tree and scroll; atomic structure save; dirty warning; table results; mobile layout; observer read-only');
 } finally {await browser.close();}
})().catch(error => {console.error(error);process.exit(1);});
