const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const c=JSON.parse(process.env.EQUIPMENT_BROWSER_CONFIG);
const day=n=>{const d=new Date(c.day+'T12:00:00Z');d.setUTCDate(d.getUTCDate()+n);return d.toISOString().slice(0,10);};
const fact=n=>c.base+c.fact+'?construction_object='+c.object+'&date='+day(n)+'&section=mechanization';
(async()=>{
 const browser=await chromium.launch({executablePath:c.chromium,headless:true,args:['--no-sandbox']});
 try{
  const context=await browser.newContext({viewport:{width:1500,height:1100}});
  await context.route('**/*',route=>route.request().url().startsWith(c.base)?route.continue():route.abort());
  await context.addCookies([{name:'sessionid',value:c.cookie,url:c.base}]);
  const page=await context.newPage();
  await page.goto(fact(0));
  await page.getByRole('link',{name:'Назначения и состояния техники',exact:true}).click();
  await page.locator('#id_new_equipment').selectOption(String(c.machine));
  await page.locator('#id_new_work').selectOption(String(c.work));
  await page.locator('#id_new_activity').fill('Разработка грунта по назначению');
  await page.getByRole('button',{name:'Сохранить назначение',exact:true}).click();
  await page.locator('section[id^=assignment-]').waitFor();
  await page.getByRole('link',{name:'Факт техники за день',exact:true}).click();
  const row=page.locator('[data-rows=equipment] details').first();
  assert(!(await row.getAttribute('open')));
  assert((await row.textContent()).includes('Подготовлено из назначения'));
  assert(await row.locator('[name=equipment-0-equipment]').isDisabled());
  await page.getByRole('button',{name:'Сохранить и подтвердить направление',exact:true}).click();
  await page.getByText('Факт подтверждён.',{exact:true}).waitFor();
  if(process.env.EQUIPMENT_SCREENSHOT)await page.screenshot({path:process.env.EQUIPMENT_SCREENSHOT,fullPage:true});
  await page.getByRole('link',{name:'Назначения и состояния техники',exact:true}).click();
  const state=page.locator('section[id^=assignment-] details').filter({has:page.locator('summary',{hasText:'Изменить состояние'})});
  await state.locator('summary').click();
  await state.locator('[name=effective_date]').fill(day(1));
  await state.locator('[name=state]').selectOption('REPAIR');
  await state.locator('[name=reason]').fill('Ремонт гидравлики на несколько дней');
  await state.getByRole('button',{name:'Сохранить состояние со смены 1',exact:true}).click();
  await page.locator('section[id^=assignment-]').waitFor();
  await page.goto(fact(1));
  assert.equal(await page.locator('[name=equipment-0-state]').inputValue(),'REPAIR');
  await page.getByRole('button',{name:'Сохранить и подтвердить направление',exact:true}).click();
  await page.getByText('Факт подтверждён.',{exact:true}).waitFor();
  await page.goto(fact(2));
  const deviation=page.locator('[data-rows=equipment] details').first();
  await deviation.locator('summary').click();
  await deviation.locator('[name=equipment-0-state]').selectOption('IDLE');
  await deviation.locator('[name=equipment-0-activity]').fill('Простой только за этот день');
  await page.getByRole('button',{name:'Сохранить и подтвердить направление',exact:true}).click();
  await page.getByText('Факт подтверждён.',{exact:true}).waitFor();
  await page.goto(fact(3));
  assert.equal(await page.locator('[name=equipment-0-state]').inputValue(),'REPAIR');
  console.log('PASS: one-time assignment → unchanged daily confirmation → persistent repair → one-day exception → unchanged following-day state');
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exit(1);});
