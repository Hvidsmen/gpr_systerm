const {chromium}=require('playwright');
(async()=>{
 const cfg=JSON.parse(process.env.INLINE_BROWSER_CONFIG);
 const browser=await chromium.launch({executablePath:cfg.chromium,headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1600,height:1100}});
 await context.addCookies([{name:'sessionid',value:cfg.admin_cookie,url:cfg.base}]);
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',async dialog=>{errors.push('Unexpected popup: '+dialog.type());await dialog.dismiss();});
 await page.route('https://**/*',route=>route.abort());
 const assert=(value,message)=>{if(!value)throw Error(message);};
 await page.goto(cfg.base+cfg.monthly,{waitUntil:'networkidle'});
 await page.locator('[data-expand-allocations]').click();
 const item=()=>page.locator('[data-work-resource-target][data-resource-item="'+cfg.item+'"]');
 await item().locator('[data-resource-card]').first().waitFor();
 assert((await item().innerText()).includes(cfg.equipment),'Assigned equipment is missing below its work');
 assert((await item().innerText()).includes(cfg.position),'Captured crew is missing below its work');
 await item().getByRole('button',{name:'Изменить',exact:true}).click();
 let editor=page.locator('[data-inline-resource-editor]');
 await editor.locator('[name=count]').fill('3');
 await page.locator('#work-rows [name$="-quantity"]').first().fill('5');
 assert(await editor.locator('[name=count]').inputValue()==='3','Monthly volume rebuild lost resource edits');
 assert(await editor.locator('[name=count]').evaluate(e=>e.form.id)==='work-resource-form','Inline controls belong to monthly form');
 assert(!await page.locator('#allocation-editor').evaluate(e=>Array.from(new FormData(e).keys()).includes('count')),'Inline resource value leaked into monthly payload');
 const saved=page.waitForResponse(r=>r.url().includes('/resource-assignment/')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
 assert((await saved).ok(),'Inline resource save failed');
 await editor.waitFor({state:'detached'});
 assert(await page.locator('#work-rows [name$="-quantity"]').first().inputValue()==='5','Resource save lost monthly work quantity');
 assert((await item().innerText()).includes('3 ед.'),'Saved count did not update under work');
 assert((await page.locator('#resource-rows-equipment').innerText()).includes('3 ед.'),'Saved count did not update common equipment');
 assert((await page.locator('#resource-rows-labor').innerText()).includes('3 чел.'),'Crew count did not update common people');
 await item().getByRole('button',{name:'Изменить',exact:true}).click();
 await editor.locator('[name=start_date]').fill('2025-12-01');
 const invalid=page.waitForResponse(r=>r.url().includes('/resource-assignment/')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
 assert((await invalid).status()===400,'Invalid quantity was accepted');
 await editor.getByRole('alert').waitFor({state:'visible'});
 await editor.getByRole('button',{name:'Отмена',exact:true}).click();
 await item().getByRole('button',{name:'Должность',exact:true}).click();
 await editor.locator('[name=position]').selectOption(String(cfg.position_id));
 await editor.locator('[name=count]').fill('2');
 const added=page.waitForResponse(r=>r.url().includes('/resource-assignment/')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'Сохранить ресурс',exact:true}).click();
 assert((await added).ok(),'Adding people inline failed');
 await editor.waitFor({state:'detached'});
 assert(await item().locator('[data-resource-card]').count()===2,'New people not shown under work');
 await item().locator('[data-resource-card]').last().getByRole('button',{name:'Изменить',exact:true}).click();
 await editor.getByRole('button',{name:'Удалить назначение',exact:true}).click();
 const removed=page.waitForResponse(r=>r.url().includes('/resource-assignment/')&&r.request().method()==='POST');
 await editor.getByRole('button',{name:'Подтвердить удаление',exact:true}).click();
 assert((await removed).ok(),'Inline delete failed');
 await editor.waitFor({state:'detached'});
 assert(await item().locator('[data-resource-card]').count()===1,'Deleted assignment remains under work');
 await context.clearCookies();await context.addCookies([{name:'sessionid',value:cfg.manager_cookie,url:cfg.base}]);
 await page.goto(cfg.base+cfg.detail,{waitUntil:'networkidle'});
 await page.locator('#work-resources [data-resource-work-plan]').first().waitFor();
 assert((await page.locator('#work-resources').innerText()).includes('01.2026'),'Manager cannot see monthly work plan');
 assert((await page.locator('#work-resources').innerText()).includes(cfg.item_unit),'Manager cannot see work units');
 assert(await page.locator('[data-resource-work-plan] input').count()===0,'Manager can edit planned volumes in resource preparation');
 assert((await item().innerText()).includes('3 ед.'),'Manager cannot see assigned resources under work');
 await context.clearCookies();await context.addCookies([{name:'sessionid',value:cfg.planner_cookie,url:cfg.base}]);
 await page.goto(cfg.base+cfg.monthly,{waitUntil:'networkidle'});
 await page.locator('[data-expand-allocations]').click();
 await item().locator('[data-resource-card]').first().waitFor();
 assert(await item().getByRole('button',{name:'Изменить',exact:true}).count()===0,'Planner can edit manager resources');
 assert(!errors.length,errors.join('\n'));
 console.log('PASS: resources and crew below work; inline add/edit/delete; common totals; unsaved monthly volumes; form ownership; validation; manager work plan; planner read-only; no popups or JS errors.');
 await browser.close();
})().catch(e=>{console.error(e.stack);process.exit(1)});
